class SectionSelect(forms.Select):
    def create_option(
        self, name, value, label, selected, index, subindex=None, attrs=None
    ):
        option = super().create_option(
            name, value, label, selected, index, subindex=subindex, attrs=attrs
        )
        if value:
            instance = getattr(value, "instance", None)
            if instance and hasattr(instance, "subject_id"):
                option["attrs"]["data-subject-id"] = str(instance.subject_id)
        return option


class TopicImportForm(forms.Form):
    MAX_FILE_SIZE = 5 * 1024 * 1024  # 5 MB

    subject = forms.ModelChoiceField(
        queryset=Subject.objects.all(),
        label="Subject",
        empty_label="--- Select Subject ---",
    )
    section = forms.ModelChoiceField(
        queryset=Section.objects.select_related("subject").all(),
        label="Section",
        empty_label="--- Select Section ---",
        widget=SectionSelect,
    )
    file = forms.FileField(
        label="JSON file",
        help_text="Upload .json file generated by medcore-content (max 5 MB).",
    )
    status = forms.ChoiceField(
        choices=Topic.Status.choices,
        initial=Topic.Status.DRAFT,
        label="Topic status",
    )
    access_level = forms.ChoiceField(
        choices=Topic.AccessLevel.choices,
        initial=Topic.AccessLevel.DEMO,
        label="Topic access level",
    )

    def clean(self):
        cleaned_data = super().clean()
        subject = cleaned_data.get("subject")
        section = cleaned_data.get("section")
        if subject and section:
            if section.subject_id != subject.id:
                self.add_error(
                    "section", "Selected section does not belong to selected subject."
                )
        return cleaned_data

    def clean_file(self):
        uploaded_file = self.cleaned_data.get("file")
        if not uploaded_file:
            raise forms.ValidationError("Please choose a JSON file to import.")
        if uploaded_file.size > self.MAX_FILE_SIZE:
            raise forms.ValidationError("File is too large. Maximum size is 5 MB.")
        if not uploaded_file.name.lower().endswith(".json"):
            raise forms.ValidationError("Only .json files are supported.")
        return uploaded_file


@admin.register(Topic)
class TopicAdmin(ContentPermissionMixin, admin.ModelAdmin):
    change_list_template = "admin/content/topic/change_list.html"
    list_display = (
        "id",
        "title",
        "section",
        "position",
        "status",
        "access_level",
    )
    list_filter = ("status", "access_level", "section__subject")
    search_fields = ("title", "slug")
    readonly_fields = ("slug", "position", "created_at", "updated_at")

    def get_urls(self):
        urls = super().get_urls()
        custom_urls = [
            path(
                "import-json/",
                self.admin_site.admin_view(self.import_json_view),
                name="content_topic_import_json",
            ),
        ]
        return custom_urls + urls

    def import_json_view(self, request):
        if not self._has_content_access(request):
            raise PermissionDenied

        if request.method == "POST":
            form = TopicImportForm(request.POST, request.FILES)
            if form.is_valid():
                uploaded_file = form.cleaned_data["file"]
                try:
                    content_bytes = uploaded_file.read()
                    data = json.loads(content_bytes.decode("utf-8"))
                except json.JSONDecodeError as exc:
                    form.add_error("file", f"Invalid JSON format: {exc.msg}")
                except UnicodeDecodeError:
                    form.add_error("file", "File encoding must be UTF-8.")
                else:
                    try:
                        result = import_study_document(
                            document=data,
                            section=form.cleaned_data["section"],
                            status=form.cleaned_data["status"],
                            access_level=form.cleaned_data["access_level"],
                            actor=request.user,
                        )
                        action_word = "Imported" if result.created else "Updated"
                        self.message_user(
                            request,
                            f'{action_word} "{result.topic.title}": '
                            f"{result.blocks_count} blocks, "
                            f"{result.flashcards_count} flashcards, "
                            f"{result.questions_count} questions, "
                            f"{result.answers_count} answers.",
                            messages.SUCCESS,
                        )
                        return redirect("admin:content_topic_change", result.topic.pk)
                    except ContentImportError as exc:
                        form.add_error(None, exc.message)
                    except Exception as exc:
                        form.add_error(None, str(exc))
        else:
            form = TopicImportForm()

        context = {
            **self.admin_site.each_context(request),
            "opts": self.model._meta,
            "form": form,
            "title": "Import Medcore JSON",
        }
        return TemplateResponse(
            request, "admin/content/topic/import_json.html", context
        )

    def save_model(self, request, obj, form, change) -> None:
        services.save_topic(
            form.cleaned_data["section"],
            title=form.cleaned_data["title"],
            description=form.cleaned_data.get("description") or "",
            status=form.cleaned_data["status"],
            access_level=form.cleaned_data["access_level"],
            cover=form.cleaned_data.get("cover"),
            cover_provided=True,
            instance=obj,
        )


